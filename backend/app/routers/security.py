from typing import Optional
from fastapi import APIRouter, Depends, Query
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy import select, desc
from app.database import get_db
from app.models.entities import User, SecurityEvent
from app.core.rbac import get_current_user

router = APIRouter(prefix="/security", tags=["Web & API Security Gateway"])


@router.get("/events")
async def list_security_events(
    severity: Optional[str] = None,
    event_type: Optional[str] = None,
    limit: int = Query(50, ge=1, le=200),
    user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """Lists normalized security events generated by gateway and application activity."""
    query = (
        select(SecurityEvent)
        .where(SecurityEvent.organization_id == user.organization_id)
        .order_by(desc(SecurityEvent.timestamp))
        .limit(limit)
    )
    if severity:
        query = query.where(SecurityEvent.severity == severity)
    if event_type:
        query = query.where(SecurityEvent.event_type == event_type)

    res = await db.execute(query)
    events = res.scalars().all()
    return events


@router.get("/gateway-status")
async def get_gateway_status(user: User = Depends(get_current_user)):
    """Returns active security gateway status, active WAF inspection filters, and rate limiting rules."""
    return {
        "status": "ONLINE",
        "waf_rules_active": [
            "SQL_INJECTION_DETECTOR",
            "XSS_SCRIPT_SANITIZER",
            "PATH_TRAVERSAL_PREVENTER",
            "CREDENTIAL_STUFFING_THROTTLER"
        ],
        "rate_limit_policy": {
            "default_window_seconds": 60,
            "api_max_requests_per_minute": 150,
            "auth_max_requests_per_minute": 20,
            "temporary_block_duration_seconds": 30
        },
        "security_headers_enforced": [
            "Strict-Transport-Security",
            "X-Content-Type-Options: nosniff",
            "X-Frame-Options: DENY",
            "Content-Security-Policy",
            "Referrer-Policy: strict-origin-when-cross-origin"
        ]
    }
